/* Deterministic ESM bundles for dashboard paste and Pages direct-upload ZIPs. */
'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),esbuild=require('esbuild');
function bundle(entry){
 const result=esbuild.buildSync({absWorkingDir:root,entryPoints:[entry],bundle:true,write:false,
  format:'esm',platform:'neutral',target:'es2022',treeShaking:false,keepNames:true,
  metafile:true,legalComments:'inline',logLevel:'silent'});
 if(result.outputFiles.length!==1)throw Error('Worker must be self-contained');
 const dependencies=Object.keys(result.metafile.inputs).sort(),hash=crypto.createHash('sha256');
 for(const name of dependencies){hash.update(name+'\0');hash.update(fs.readFileSync(path.resolve(root,name)));hash.update('\0');}
 return '// Generated by scripts/bundle-worker.cjs; edit canonical Worker modules.\n'+
  '// Source SHA256: '+hash.digest('hex')+'\n'+result.outputFiles[0].text;
}
module.exports={bundle};
if(require.main===module){
 const [, ,entry,out,...args]=process.argv;
 if(!entry||!out)throw Error('Usage: node scripts/bundle-worker.cjs entry output [--check]');
 const content=bundle(entry),destination=path.resolve(root,out);
 if(args.includes('--check')){if(fs.readFileSync(destination,'utf8')!==content)throw Error('Regenerate '+out);}
 else fs.writeFileSync(destination,content);
 console.log((args.includes('--check')?'Verified ':'Bundled ')+out);
}
