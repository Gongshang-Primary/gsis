/* Keep Apps Script/browser models canonical; publish explicit Worker ESM wrappers. */
'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const roster=[
 ['GSISRoster','roster.js'],['GSISRosterOperations','roster-operations.js'],
 ['GSISRosterAllocation','roster-allocation.js'],['GSISRosterStapler','roster-stapler.js'],
 ['GSISRosterStatistics','roster-statistics.js'],['GSISRosterInbox','roster-inbox.js'],
 ['GSiSEdgeNotifications','edge-notification-model.js']
];
function wrapper(entries){
 const names=entries.map(([name])=>name);
 const lookup=entries.map(([name,file])=>`case './${file}': return ${name};`).join('\n');
 return '// Generated by scripts/build-edge-modules.cjs. Edit shared sources.\n'+
  `function sharedRequire(id){switch(id){${lookup}\ndefault:throw new Error('Unknown shared module: '+id);}}\n`+
  entries.map(([name,file])=>`const ${name}=(()=>{const module={exports:{}};const require=sharedRequire;\n${fs.readFileSync(path.join(root,'shared',file),'utf8')}\nreturn module.exports;})();\n`).join('\n')+
  `export {${names.join(',')}};\n`;
}
for(const folder of ['public','roster-update/public'])fs.writeFileSync(path.join(root,folder,'edge-store.js'),wrapper([['GSiSEdgeStore','edge-store.js'],['GSiSRosterImport','roster-import.js'],['GSiSRosterMirror','roster-mirror.js']]));
fs.writeFileSync(path.join(root,'roster-update/public/edge-roster-domain.js'),wrapper(roster));
// Both gateways use the same published Deploy authority; no cross-origin callback.
for(const file of ['edge-deploy.js','edge-deploy-domain.js','edge-deploy-sha256.js']){
 const source=path.join(root,'public',file);
 if(fs.existsSync(source))fs.copyFileSync(source,path.join(root,'roster-update/public',file));
}
for(const folder of ['public','roster-update/public'])fs.copyFileSync(path.join(root,'shared/edge-venues-fence.js'),path.join(root,folder,'edge-venues-fence.js'));
for(const [folder,domain,label] of [['public','deploy','Deploy'],['roster-update/public','roster','Roster']]){
 for(const ext of ['js','css'])fs.copyFileSync(path.join(root,'shared','edge-setup.'+ext),path.join(root,folder,'edge-setup.'+ext));
 const html=fs.readFileSync(path.join(root,'shared/edge-setup.html'),'utf8').replaceAll('__DOMAIN__',domain).replaceAll('__DOMAIN_LABEL__',label);
 fs.writeFileSync(path.join(root,folder,'edge-setup.html'),html);
}
console.log('Generated shared Worker modules from canonical models');
