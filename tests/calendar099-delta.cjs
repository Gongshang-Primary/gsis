'use strict';
const assert=require('node:assert/strict');
const {makeHarness}=require('./calendar/backend_harness.cjs');
const h=makeHarness(),admin=h.actor('admin'),viewer=h.actor('teacher');
const send=(actor,action,payload)=>JSON.parse(h.sandbox.doPost({postData:{contents:JSON.stringify({proxySecret:'synthetic-secret',actor,action,payload})}}).text);
let result=send(admin,'calendarChangesAuthorize',{year:2026});
assert.equal(result.ok,true,result.error);assert.equal(result.result.authorized,true);
const known=h.event('E1');
result=send(admin,'calendarChangesDelta',{year:2026,known:[{id:'E1',revision:known._changeRevision||known._revision},{id:'removed-client-row',revision:'old'}]});
assert.equal(result.ok,true,result.error);
assert.equal(result.result.events.some(e=>e.EventID==='E1'),false,'Unchanged rows are absent from delta');
assert(result.result.removed.includes('removed-client-row'));
assert.equal(result.result.snapshot.events,undefined,'Metadata and changed rows are returned separately');
assert.equal(result.result.snapshot.selectedYear,2026);
const beforeSync=h.event('E1');
h.seed('Events',[{...h.base,EventID:'E1',StaffSyncState:'PENDING_SYNC'}]);
const afterSync=h.event('E1');assert.equal(beforeSync._revision,afterSync._revision,'Provider state does not change edit concurrency');assert.notEqual(beforeSync._changeRevision,afterSync._changeRevision,'Provider state must change the live-data revision');
result=send(admin,'calendarChangesDelta',{year:2026,known:[{id:'E1',revision:beforeSync._changeRevision}]});assert.equal(result.ok,true,result.error);assert.equal(result.result.events[0].StaffSyncState,'PENDING_SYNC');
h.seed('Events',[{...h.base,EventID:'E1',Status:'DRAFT',StaffTitle:'Hidden title'}]);
result=send(viewer,'calendarChangesDelta',{year:2026,known:[{id:'E1',revision:known._changeRevision||known._revision}]});
assert.equal(result.ok,true,result.error);assert(result.result.removed.includes('E1'),'Losing visibility removes an already-known row');
assert(!JSON.stringify(result).includes('Hidden title'));
assert.equal(send(admin,'calendarChangesDelta',{year:2026,known:Array.from({length:2001},(_,i)=>({id:'E'+i,revision:'x'}))}).status,400);
h.seed('Years',[{Year:2026,Status:'DRAFT',ReleasedToTeachers:'No'}]);
assert.equal(send(viewer,'calendarChangesAuthorize',{year:2026}).status,403,'Each subscription rechecks current year access');
assert.equal(send(viewer,'calendarChangesDelta',{year:2026,known:[]}).status,403,'Each delta rechecks current year access');
h.seed('Events',Array.from({length:2001},(_,i)=>({...h.base,EventID:'LARGE-'+i})));
assert.equal(send(admin,'calendarChangesDelta',{year:2026,known:[]}).status,413,'Large years require explicit manual refresh, never truncated live data');
console.log('PASS Calendar source delta: fresh permissions, bounded known rows, changed rows only, visibility removals and source metadata');
