'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const {JSDOM} = require('jsdom');
const read = p => fs.readFileSync(p, 'utf8');
const p = JSON.parse(read('package.json')), v = '0.9.9';
const base = '50c977d79c9756dfdbee91f2922f0cd89ab6e903';
const lock = JSON.parse(read('package-lock.json'));
assert.equal(p.gsisRelease, v); assert.equal(p.version, v);
assert.equal(lock.version, v); assert.equal(lock.packages[''].version, v);
assert.equal(p.gsisBaseline, '0.9.8q'); assert.equal(p.gsisSourceBase, base);
assert.equal(p.gsisPatchSourceBase, base); assert.equal(p.gsisPackageKind, 'full-suite');
assert.equal(Object.keys(p.gsisComponentVersions).length, 18);
assert(Object.values(p.gsisComponentVersions).every(value => value === v));
assert.deepEqual(new Set(p.gsisPatchComponents), new Set(Object.keys(p.gsisComponentVersions)));
assert.equal(p.gsisSeparatePackages.length, 1);
assert.equal(p.gsisSeparatePackages[0].name, 'GSiS_v0.9.9_Timetable_Preparation.zip');
assert.equal(p.gsisSeparatePackages[0].productionInstallation, false);
const spec = JSON.parse(read('release-installation-manifest.json'));
assert.equal(Object.keys(spec.frontends).length, 9); assert.equal(spec.backends.length, 6);
assert.equal(Object.keys(spec.workers).length, 3); assert.deepEqual(spec.migrations, []);
for (const folder of Object.values(spec.frontends)) assert(read(folder + '/index.html').includes('v' + v), folder + ' visible version');
assert(read('calendar-update/public/app.js').includes("FRONTEND_VERSION = '" + v + "'"));
assert(read('calendar-update/public/_worker.js').includes("WORKER_VERSION = '" + v + "'"));
assert(read('calendar-backend/Code.gs').includes("RELEASE_VERSION: '" + v + "'"));
const guide = new JSDOM(read('SETUP_v' + v + '.html')).window.document;
const markdown = read('SETUP_v' + v + '.md');
assert.equal(guide.querySelectorAll('script,iframe,form').length, 0);
assert.equal(guide.querySelectorAll('h2').length, (markdown.match(/^## /gm) || []).length);
for (const app of spec.backends) assert(guide.body.textContent.includes(app + '_Backend_v' + v + '.gs'), app + ' backend install reference');
for (const phrase of ['Google', 'CALENDAR_SYNC_CONTINUE', 'rehearsal']) assert(guide.body.textContent.includes(phrase), phrase);
const summary = JSON.parse(read('RELEASE_SUMMARY.json'));
assert.equal(summary.version, v); assert.equal(summary.componentCount, 18);
assert.equal(summary.baseline, '0.9.8q'); assert.equal(summary.baselineCommit, base);
assert.equal(summary.productionAuthorities.roster, 'Google');
assert.equal(summary.productionAuthorities.calendar, 'Google');
assert.equal(summary.productionAuthorities.deploy, 'unchanged configured authority');
for (const key of ['productionDeployed', 'authorityCutoverPerformed', 'messagesSent', 'liveRecordsChanged', 'newInfrastructureDeployed', 'reliefLedgerMigrated']) assert.equal(summary[key], false, key);
assert.equal(summary.optionalInfrastructurePrepared, true);
assert(read('README.md').includes('docs/v099/SETUP.html'));
assert(read('docs/v099/RECOVERY_HISTORY.md').includes(base));
console.log('PASS 0.9.9 metadata:18 matched production components, separate shadow preparation, offline setup, unchanged Google authority.');
