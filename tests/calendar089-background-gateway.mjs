import {toWorkerModuleURL} from './helpers/worker-module.cjs';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHmac, webcrypto} from 'node:crypto';
globalThis.crypto ||= webcrypto;
const source = readFileSync(new URL('../calendar-update/public/_worker.js', import.meta.url), 'utf8');
const worker = (await import(toWorkerModuleURL('data:text/javascript;base64,' + Buffer.from(source).toString('base64')))).default;
const env = {CALENDAR_SERVICE_SECRET: 'calendar-service-test', CALENDAR_APPS_SCRIPT_URL: 'https://script.google.com/macros/s/test/exec', CALENDAR_PROXY_SECRET: 'proxy-test'};
let calls = 0;
globalThis.fetch = async (_url, options) => {
  calls++;
  const body = JSON.parse(options.body);
  assert.equal(body.service, 'gsis-calendar-sync-worker-v1');
  assert.equal(body.action, 'calendarSyncContinue');
  assert.equal(body.calendarServiceSecret, env.CALENDAR_SERVICE_SECRET);
  assert.equal(body.actor, undefined);
  return new Response(JSON.stringify({ok: true, result: {idle: true}}), {headers: {'Content-Type': 'application/json'}});
};
const payload = JSON.stringify({purpose: 'gsis-calendar-sync-wake-v1', timestamp: Date.now(), nonce: crypto.randomUUID()});
const signature = createHmac('sha256', env.CALENDAR_SERVICE_SECRET).update(payload).digest('hex');
const send = (body, bindings = env) => worker.fetch(new Request('https://calendar.test/api/internal/sync-continue', {method: 'POST', body: JSON.stringify(body)}), bindings);
assert.equal((await send({payload, signature: '0'.repeat(64)})).status, 401);
assert.equal(calls, 0);
assert.equal((await send({payload, signature})).status, 200);
assert.equal(calls, 1);
const stale = JSON.stringify({purpose: 'gsis-calendar-sync-wake-v1', timestamp: Date.now() - 180000, nonce: crypto.randomUUID()});
assert.equal((await send({payload: stale, signature: createHmac('sha256', env.CALENDAR_SERVICE_SECRET).update(stale).digest('hex')})).status, 401);
assert.equal(calls, 1);
assert.equal((await send({payload, signature}, {...env, CALENDAR_SERVICE_SECRET: ''})).status, 503);
assert.equal(calls, 1);
console.log('PASS Calendar background gateway: signed bounded wake, stale/invalid signature denied, no user identity forwarded, disabled by missing secret');
