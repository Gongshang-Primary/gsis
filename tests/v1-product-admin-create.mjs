import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { productSuite, origin } from './v1-product/suite.mjs';
const suite = await productSuite({bindings:{HOSTED_DOMAIN:'example.invalid'}});
let browser;
try {
  const admin = await suite.seedAccount('account-admin');
  browser = await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage'],executablePath:process.env.GSIS_BROWSER_EXECUTABLE||process.env.ROSTER_TEST_CHROMIUM||undefined});
  const context = await browser.newContext();
  await context.addCookies([{name:'__Host-gsis_session',value:admin.token,domain:'gsis.example.invalid',path:'/',secure:true,httpOnly:true,sameSite:'Lax'}]);
  let loseResponse = true;
  const writes=[];
  await context.route('**/*',async route=>{
    const r=route.request();
    if(!r.url().startsWith(origin+'/')) return route.abort();
    const write=r.url().endsWith('/api/core/admin/accounts')&&r.method()==='POST';
    if(write) writes.push(JSON.parse(r.postData()));
    const result=await suite.mf.dispatchFetch(r.url(),{method:r.method(),headers:await r.allHeaders(),body:['GET','HEAD'].includes(r.method())?undefined:r.postDataBuffer()});
    if(write&&loseResponse&&result.ok){loseResponse=false;await result.arrayBuffer();return route.abort();}
    const headers=Object.fromEntries(result.headers);delete headers['transfer-encoding'];
    return route.fulfill({status:result.status,headers,body:Buffer.from(await result.arrayBuffer())});
  });
  const page=await context.newPage();
  await page.goto(origin+'/admin/');
  await page.locator('#addAccount').click();
  assert.equal(await page.locator('#newAdmin').isChecked(),false);
  await page.locator('#newEmail').fill('second@example.invalid');
  await page.locator('#newSubject').fill('google-second');
  await page.locator('#newAdmin').check();
  await page.locator('#reason').fill('Synthetic additional Admin');
  await page.locator('#accountForm button[type=submit]').click();
  await page.waitForFunction(()=>document.querySelector('#accountStatus').textContent.includes('retained for retry'));
  await page.locator('#accountForm button[type=submit]').click();
  await page.waitForFunction(()=>document.querySelector('#accountForm').hidden);
  assert.equal(writes.length,2);
  assert.deepEqual(writes[0],writes[1],'lost response retries identical operation and account IDs');
  let list=await suite.request(admin,'core','/admin/accounts');
  const rows=list.body.data.rows||list.body.data.accounts;
  const created=rows.filter(x=>x.email==='second@example.invalid');
  assert.equal(created.length,1,'one durable account after retry');
  assert((created[0].capabilities||created[0].grants).includes('admin'));
  await page.getByRole('row').filter({hasText:'second@example.invalid'}).getByRole('button',{name:'Edit',exact:true}).click();
  assert.equal(await page.locator('#newIdentity').isVisible(),false);
  await page.locator('#capabilities').fill('');
  await page.locator('#reason').fill('Synthetic removal');
  await page.locator('#accountForm button[type=submit]').click();
  await page.waitForFunction(()=>document.querySelector('#accountForm').hidden);
  list=await suite.request(admin,'core','/admin/accounts');
  const updated=(list.body.data.rows||list.body.data.accounts).find(x=>x.email==='second@example.invalid');
  assert(!(updated.capabilities||updated.grants).includes('admin'));
  await page.locator('#addAccount').click();
  await page.locator('#newEmail').fill('foreign@other.invalid');
  await page.locator('#newSubject').fill('google-foreign');
  await page.locator('#newAdmin').check();
  await page.locator('#reason').fill('Synthetic wrong domain');
  await page.locator('#accountForm button[type=submit]').click();
  await page.waitForFunction(()=>document.querySelector('#accountStatus').textContent.includes('retained for retry'));
  list=await suite.request(admin,'core','/admin/accounts');
  assert(!(list.body.data.rows||list.body.data.accounts).some(x=>x.email==='foreign@other.invalid'));
  console.log('PASS Admin UI creates explicit Admin, preserves committed operation across lost response, edits existing account and rejects foreign domain; synthetic Workers/D1 only');
} finally { await browser?.close(); await suite.close(); }
